/* VA Academy quota office — STAGING; internal VA Admin Operations only.
   No direct writes to bookings, tickets, orders or cash. Group / commissioner
   seats are reserved atomically in the SAME lock domain as public Native HOLD V2.
   KG-7 / KG-8 RPC are already installed on Supabase; this client invokes
   them exclusively through the protected VA Admin Operations Edge Function.
*/
(() => {
  'use strict';
  const el = (id) => document.getElementById(id);
  let pendingRequestId = crypto.randomUUID();
  let busy = false;
  let selectedSeance = '';

  function text(node, value) { node.textContent = String(value ?? ''); }
  function button(label, onClick, disabled=false) {
    const x = document.createElement('button');
    x.className = 'btn ghost'; x.type = 'button';
    x.textContent = label; x.disabled = disabled;
    x.addEventListener('click', onClick);
    return x;
  }
  function td(tr, value) {
    const c = document.createElement('td');
    c.style.cssText = 'padding:8px;border-bottom:1px solid #64748b44';
    text(c, value); tr.appendChild(c); return c;
  }
  function message(value, error=false) {
    const n = el('vaAcademyMsg'); if (!n) return;
    text(n,value); n.style.color=error?'#fda4af':'#86efac';
  }
  function parseSeats(s) {
    return String(s||'').split(/[\s,;]+/).map(v=>v.trim().toUpperCase()).filter(Boolean);
  }
  function checkedSeance() {
    const sid = String(el('seanceSelect')?.value||'').trim();
    if (!sid || sid!==selectedSeance) throw new Error('Оберіть сеанс Академії руху ще раз');
    return sid;
  }
  async function call(name, params) {
    if (!window.VAAdminOps?.rpc) throw Error('VA Admin Operations недоступний');
    const result = await window.VAAdminOps.rpc(name, params);
    if (!result?.ok) throw new Error(result?.code || 'Операція не виконана');
    return result;
  }
  // KG documents are generated by restricted RPC, never by direct public table writes.
  const htmlEsc = (v) => String(v ?? '').replace(/[&<>"']/g,
    (c) => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const money = (v) => Number(v||0).toLocaleString('uk-UA',
    {minimumFractionDigits:2,maximumFractionDigits:2});
  async function issueKG7(b) {
    if (!confirm(`Оформити КГ-7 для ${b.organization||b.agent||'комісіонера'}?\n${(b.seats||[]).join(', ')}`)) return;
    try {
      const result=await call('va_academy_kg7_issue_v1', {
        p_request_id:crypto.randomUUID(),p_booking_id:b.id
      });
      message(`КГ-7 ${result.doc_no} оформлено. Документ можна роздрукувати.`);
      await refresh();
      window.dispatchEvent(new Event('va-academy-office-changed'));
    } catch(e) {message(`КГ-7: ${e.message||e}`,true);}
  }
  async function returnKG8(b) {
    const original=Array.isArray(b.seats)?b.seats:[];
    const answer=prompt('Вкажіть місця для повернення за КГ-8 (через кому):',original.join(', '));
    if (answer===null)return;
    const seats=parseSeats(answer);
    if (!seats.length || new Set(seats).size!==seats.length ||
        seats.some(s=>!original.includes(s))) {
      message('КГ-8: вкажіть тільки видані місця без повторів',true);return;
    }
    if (!confirm(`Оформити КГ-8 на повернення ${seats.length} місць?`))return;
    try {
      const result=await call('va_academy_kg8_return_v1', {
        p_request_id:crypto.randomUUID(),p_booking_id:b.id,p_return_seats:seats
      });
      message(`КГ-8 ${result.doc_no}: повернуто ${seats.length} місць, ${money(result.amount)} грн`);
      await refresh();
      window.dispatchEvent(new Event('va-academy-office-changed'));
    } catch(e) {message(`КГ-8: ${e.message||e}`,true);}
  }
  async function printKG(b,docType) {
    // Open synchronously from the button click (avoids popup blocker after await).
    const win=window.open('','_blank');
    if (!win){message('Дозвольте спливаючі вікна для друку',true);return;}
    try {
      const doc=await call('va_academy_kg_document_v1',{
        p_booking_id:b.id,p_doc_type:docType,p_doc_id:null
      });
      const lines=(doc.rows||[]).map((r,i)=>
        `<tr><td>${i+1}</td><td>${htmlEsc(r.seat)}</td><td class="num">${money(r.price)}</td></tr>`
      ).join('');
      win.document.open();
      win.document.write(`<!doctype html><html lang="uk"><head><meta charset="utf-8">
<title>${htmlEsc(docType.toUpperCase())} ${htmlEsc(doc.doc_no)}</title>
<style>body{font:14px Arial,sans-serif;color:#111;margin:24px}h1{text-align:center}
.caption{font-size:12px;color:#444}table{width:100%;border-collapse:collapse;margin:18px 0}
 td,th{border:1px solid #222;padding:7px;text-align:left}.num{text-align:right}
.signs{display:flex;justify-content:space-between;margin-top:55px}
@media print{button{display:none}body{margin:12mm}}</style></head><body>
<button onclick="window.print()">Друкувати</button>
<div class="caption">ВАШ АДМІН • продаж квоти «Академія руху»</div>
<div class="caption">Обліковий документ для внутрішнього документообігу VA</div>
<h1>${htmlEsc(docType.toUpperCase())} № ${htmlEsc(doc.doc_no)}</h1>
<p>Документ від: ${htmlEsc(doc.issued_at||'')}</p>
<p><b>Захід:</b> ${htmlEsc(doc.show)} • ${htmlEsc(doc.date)} ${htmlEsc(doc.time)}</p>
<p><b>Комісіонер:</b> ${htmlEsc(doc.organization)} • ${htmlEsc(doc.agent)}</p>
<p><b>Контакт:</b> ${htmlEsc(doc.contact_name)}</p>
${docType==='kg8'?`<p><b>Документ видачі:</b> ${htmlEsc(doc.issue_doc)}</p>`:''}
<table><thead><tr><th>№</th><th>Місце</th><th>Ціна, грн</th></tr></thead>
<tbody>${lines}</tbody></table>
<p><b>Усього місць:</b> ${doc.qty}; <b>Сума:</b> ${money(doc.amount)} грн</p>
<div class="signs"><span>Видав / Прийняв: ______________</span>
<span>Одержав / Повернув: ______________</span></div>
</body></html>`);
      win.document.close();
    } catch(e) {
      win.close(); message(`Друк ${docType.toUpperCase()}: ${e.message||e}`,true);
    }
  }
  async function refresh() {
    const sid=checkedSeance();
    const body=el('vaAcademyBody');
    if (!body) return;
    body.replaceChildren();
    const data=await call('va_academy_office_list_v1',{p_seance_id:sid});
    for (const b of data.rows || []) {
      const tr=document.createElement('tr');
      td(tr, b.organization || '—');
      td(tr, Array.isArray(b.seats)?b.seats.join(', '):'—');
      td(tr, b.amount ?? '—');
      td(tr, b.status || '—');
      td(tr, b.agent || '—');
      td(tr, b.expires_at ? new Date(b.expires_at).toLocaleString('uk-UA'):'—');
      const cell=document.createElement('td');
      cell.style.padding='8px';
      if (b.status==='reserved' && !b.issue_doc) {
        if (String(b.note||'').startsWith('[VA commissioner]')) {
          cell.append(button('Видати КГ-7',()=>issueKG7(b)));
        } else {
          cell.append(button('Скасувати', async () => {
            if (!confirm('Скасувати резерв цих місць?')) return;
            try {
              message('Скасування резерву…');
              await call('va_academy_office_cancel_v1',{p_booking_id:b.id});
              message('Резерв скасовано');await refresh();
              window.dispatchEvent(new Event('va-academy-office-changed'));
            } catch(e){message(e.message,true);}
          }));
        }
      } else if (b.status==='issued_to_partner') {
        cell.append(button('Повернути КГ-8',()=>returnKG8(b)));
        cell.append(button('Друк КГ-7',()=>printKG(b,'kg7')));
        cell.append(button('Останній КГ-8',()=>printKG(b,'kg8')));
      } else if (b.status==='partner_returned') {
        cell.append(button('Друк КГ-7',()=>printKG(b,'kg7')));
        cell.append(button('Останній КГ-8',()=>printKG(b,'kg8')));
      }
      tr.appendChild(cell); body.appendChild(tr);
    }
    if (!data.rows?.length) {
      const tr=document.createElement('tr');
      const cell=document.createElement('td'); cell.colSpan=7;
      text(cell,'Резервів VA на цей сеанс немає');
      tr.append(cell); body.append(tr);
    }
  }
  async function reserve(ev) {
    ev.preventDefault(); if (busy) return;
    const kind=el('vaAcademyKind').value;
    const agent=el('vaAcademyAgent').value.trim();
    const seats=parseSeats(el('vaAcademySeats').value);
    if (!seats.length || seats.length>100 || new Set(seats).size!==seats.length ||
        seats.some(s=>!/^P[1-9][0-9]*-M[1-9][0-9]*$/.test(s))) {
      message('Місця: 1–100 у форматі P2-M7, без повторів',true);return;
    }
    if (kind==='commissioner' && !agent) {
      message('Для комісіонера вкажіть уповноваженого з довідника VA',true); return;
    }
    const expiry=el('vaAcademyExpiry').value;
    const payload={
      p_request_id:pendingRequestId,
      p_seance_id:checkedSeance(),
      p_seats:seats,
      p_kind:kind,
      p_organization:el('vaAcademyOrg').value.trim(),
      p_contact_name:el('vaAcademyPerson').value.trim(),
      p_phone:el('vaAcademyPhone').value.trim(),
      p_email:el('vaAcademyEmail').value.trim()||null,
      p_agent:agent||null,
      p_expires_at:expiry ? new Date(expiry).toISOString() : null,
      p_note:el('vaAcademyNote').value.trim()||null,
    };
    busy=true;el('vaAcademySubmit').disabled=true;
    message('Перевіряємо квоту й резервуємо місця…');
    try {
      const result=await call('va_academy_office_reserve_v1',payload);
      message(`${result.code==='already_reserved'?'Резерв уже створено':'Резерв створено'}: ${result.seats?.length||seats.length} місць, ${result.amount} грн`);
      pendingRequestId=crypto.randomUUID();
      el('vaAcademySeats').value='';
      await refresh();
      window.dispatchEvent(new Event('va-academy-office-changed'));
    } catch(e) {
      message(`Резерв не створено: ${String(e.message||e)}. Той самий ID запиту збережено для повтору.`,true);
    } finally {busy=false;el('vaAcademySubmit').disabled=false;}
  }
  function row(name, id, type='text',placeholder='') {
    const wrap=document.createElement('label');
    wrap.style.cssText='display:flex;flex-direction:column;gap:5px;margin-bottom:9px';
    text(wrap,name);
    const input=document.createElement('input');
    input.id=id;input.type=type;input.placeholder=placeholder;
    input.style.cssText='padding:9px;border:1px solid #64748b;border-radius:7px;width:100%;background:#111827;color:white';
    wrap.append(input);return wrap;
  }
  function render(targetId='turnoverWorkspace') {
    const target=el(targetId); if(!target)return;
    const sid=String(el('seanceSelect')?.value||'').trim();
    const option=el('seanceSelect')?.selectedOptions?.[0];
    selectedSeance=sid;
    const venue=(window.SEANCES||[]).find?.(x=>String(x.id)===sid)?.venue_id;
    // VA office is fixed to Academy. The server ENFORCES this again.
    if (!sid) { text(target,'Оберіть сеанс Академії руху.');return; }
    if (venue && venue!=='academy') {text(target,'Цей розділ працює лише для Академії руху.');return;}
    const root=document.createElement('section');root.className='panel';
    const heading=document.createElement('h3');text(heading,'VA • Академія руху — резерв квоти');
    const description=document.createElement('p');
    text(description,'Внутрішні групові та комісіонерські резерви. Без оплати й випуску квитків. Перевірка місць і ціни виконується сервером. КГ-7/КГ-8 оформлюються через захищений сервер. Друк — з журналу резервів.');
    root.append(heading,description);
    const form=document.createElement('form');form.id='vaAcademyForm';
    form.style.cssText='max-width:700px;display:grid;grid-template-columns:repeat(auto-fit,minmax(220px,1fr));gap:9px';
    const kindLabel=document.createElement('label');text(kindLabel,'Тип резерву');
    kindLabel.style.cssText='display:flex;flex-direction:column;gap:5px';
    const kind=document.createElement('select');kind.id='vaAcademyKind';
    kind.style.cssText='padding:9px;border-radius:7px;background:#111827;color:white';
    for (const [val,label] of [['group','Організація / група'],['commissioner','Комісіонер VA']]) {
      const opt=document.createElement('option');opt.value=val;text(opt,label);kind.append(opt);
    }
    kindLabel.append(kind);
    form.append(kindLabel);
    form.append(row('Організація / партнер','vaAcademyOrg'));
    form.append(row('Контактна особа','vaAcademyPerson'));
    form.append(row('Телефон','vaAcademyPhone','tel'));
    form.append(row('Email','vaAcademyEmail','email'));
    form.append(row('Уповноважений / агент VA','vaAcademyAgent'));
    form.append(row('Контрольний термін (не звільняє автоматично)','vaAcademyExpiry','datetime-local'));
    form.append(row('Місця через кому','vaAcademySeats','text','P2-M7, P2-M8'));
    form.append(row('Примітка','vaAcademyNote'));
    const controls=document.createElement('div');
    const submit=document.createElement('button');submit.id='vaAcademySubmit';
    submit.type='submit';submit.className='btn green';text(submit,'Зарезервувати в квоті VA');
    controls.append(submit);form.append(controls);
    const status=document.createElement('p');status.id='vaAcademyMsg';status.setAttribute('role','status');
    root.append(form,status);
    const listTitle=document.createElement('h3');text(listTitle,'Резерви VA на цьому сеансі');root.append(listTitle);
    const refreshBtn=button('Оновити список',()=>refresh().catch(e=>message(e.message,true)));
    root.append(refreshBtn);
    const table=document.createElement('table');table.style.cssText='width:100%;font-size:13px';
    const head=document.createElement('thead');const tr=document.createElement('tr');
    for (const label of ['Організація','Місця','Сума','Статус','Агент','До','Дія']) {
      const th=document.createElement('th');text(th,label);tr.append(th);
    } head.append(tr);table.append(head);
    const tb=document.createElement('tbody');tb.id='vaAcademyBody';table.append(tb);
    const scroll=document.createElement('div');scroll.style.overflowX='auto';scroll.append(table);
    root.append(scroll);target.replaceChildren(root);
    form.addEventListener('submit',reserve);
    refresh().catch(e=>message(e.message,true));
  }
  window.VAAcademyOffice=Object.freeze({render});
})();
